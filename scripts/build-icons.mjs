// `pnpm icons` — turns the custom icon set (brand/<slug>/icons/svg/*.svg) into the typed data
// behind <Icon name="…" />. Run it after adding or changing an icon; the brand files themselves
// are never modified. Each SVG must be the kit's shape: one <g> of main lines (currentColor) and
// an optional <g data-accent> drawn in var(--icon-accent).
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const brand = process.argv[2] ?? "suatu";
const source = path.join("brand", brand, "icons", "svg");
const target = path.join("src", "components", "ui", "icons", "iconPaths.ts");

const SHAPE =
  /^<svg [^>]*viewBox="0 0 24 24"[^>]*>(?:<g>(.*?)<\/g>)?(?:<g stroke="var\(--icon-accent, currentColor\)" data-accent="true">(.*?)<\/g>)?<\/svg>\s*$/s;
const SAFE =
  /^(?:<(?:path|circle|rect|line|polyline|polygon|ellipse)(?: [a-z-]+="[^"<>]*")*\s*\/>)*$/;

const entries = readdirSync(source)
  .filter((file) => file.endsWith(".svg"))
  .sort()
  .map((file) => {
    const name = file.replace(/\.svg$/, "");
    const match = SHAPE.exec(readFileSync(path.join(source, file), "utf8"));
    if (!match) throw new Error(`${file}: not in the icon kit's format (see icons/README.md)`);
    const [, main = "", accent = ""] = match;
    // Only plain shape elements may pass into the app (they're inserted as markup).
    for (const part of [main, accent]) {
      if (!SAFE.test(part)) throw new Error(`${file}: contains something other than plain shapes`);
    }
    return `  ${JSON.stringify(name)}: { main: ${JSON.stringify(main)}, accent: ${JSON.stringify(accent)} },`;
  });

writeFileSync(
  target,
  `// Generated by scripts/build-icons.mjs from ${source.split(path.sep).join("/")} — do not edit.\n` +
    `// Run \`pnpm icons\` after changing the icon set.\n\n` +
    `export const iconPaths = {\n${entries.join("\n")}\n} as const;\n\n` +
    `export type IconName = keyof typeof iconPaths;\n`,
);
console.log(`Wrote ${entries.length} icons to ${target}`);
